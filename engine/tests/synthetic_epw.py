from __future__ import annotations

import math
from datetime import date, timedelta
from pathlib import Path

from shelter_engine.weather import standard_pressure_pa

HEADER_NOTE = ("SYNTHETIC TEST WEATHER, generated by the engine test suite. "
               "Not a measured or statistically derived year. "
               "Layer 0 supplies the real EPW.")


def _solar_altitude_azimuth(latitude_deg: float, longitude_deg: float,
                            time_zone_h: float, day_of_year: int,
                            hour: int) -> tuple[float, float]:
    latitude = math.radians(latitude_deg)
    declination = math.radians(23.45) * math.sin(
        2.0 * math.pi * (284 + day_of_year) / 365.0)
    b = 2.0 * math.pi * (day_of_year - 81) / 364.0
    equation_of_time = 9.87 * math.sin(2 * b) - 7.53 * math.cos(b) - 1.5 * math.sin(b)
    standard_meridian = 15.0 * time_zone_h
    solar_time = (hour + 0.5) + (4.0 * (longitude_deg - standard_meridian)
                                 + equation_of_time) / 60.0
    hour_angle = math.radians(15.0 * (solar_time - 12.0))
    sin_altitude = (math.sin(latitude) * math.sin(declination)
                    + math.cos(latitude) * math.cos(declination) * math.cos(hour_angle))
    sin_altitude = max(-1.0, min(1.0, sin_altitude))
    altitude = math.asin(sin_altitude)
    cos_azimuth = ((math.sin(altitude) * math.sin(latitude) - math.sin(declination))
                   / max(1e-6, math.cos(altitude) * math.cos(latitude)))
    cos_azimuth = max(-1.0, min(1.0, cos_azimuth))
    azimuth = math.degrees(math.acos(cos_azimuth))
    if hour_angle > 0.0:
        azimuth = 360.0 - azimuth
    return math.degrees(altitude), azimuth


def write_synthetic_epw(path: str | Path, latitude_deg: float = 34.15,
                        longitude_deg: float = 77.57, time_zone_h: float = 5.5,
                        elevation_m: float = 3500.0, annual_mean_c: float = 6.0,
                        annual_swing_c: float = 14.0, diurnal_swing_c: float = 14.0,
                        city: str = "SYNTHETIC-LEH", year: int = 2019) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    pressure = int(round(standard_pressure_pa(elevation_m)))
    lines = [
        f"LOCATION,{city},LADAKH,IND,SYNTHETIC-TEST-DATA,000000,"
        f"{latitude_deg:.3f},{longitude_deg:.3f},{time_zone_h:.1f},{elevation_m:.1f}",
        "DESIGN CONDITIONS,0",
        "TYPICAL/EXTREME PERIODS,0",
        "GROUND TEMPERATURES,1,0.5,,,,"
        + ",".join(f"{annual_mean_c - 3.0 + 6.0 * math.sin(2 * math.pi * (m - 4) / 12):.1f}"
                   for m in range(1, 13)),
        "HOLIDAYS/DAYLIGHT SAVINGS,No,0,0,0",
        f"COMMENTS 1,{HEADER_NOTE}",
        "COMMENTS 2,",
        "DATA PERIODS,1,1,Data,Sunday, 1/ 1,12/31",
    ]
    start = date(year, 1, 1)
    days = 366 if (year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)) else 365
    for offset in range(days):
        current = start + timedelta(days=offset)
        day_of_year = offset + 1
        seasonal = annual_mean_c - annual_swing_c * math.cos(
            2.0 * math.pi * (day_of_year - 15) / 365.0)
        for hour in range(1, 25):
            diurnal = 0.5 * diurnal_swing_c * math.cos(
                2.0 * math.pi * ((hour - 1) - 15) / 24.0)
            dry_bulb = seasonal + diurnal
            altitude, _ = _solar_altitude_azimuth(latitude_deg, longitude_deg,
                                                  time_zone_h, day_of_year, hour - 1)
            if altitude > 0.0:
                sine = math.sin(math.radians(altitude))
                direct_normal = 920.0 * (sine ** 0.28)
                diffuse = 95.0 * sine
                global_horizontal = direct_normal * sine + diffuse
            else:
                direct_normal = diffuse = global_horizontal = 0.0
            relative_humidity = max(10.0, min(95.0, 55.0 - 1.2 * dry_bulb))
            dew_point = dry_bulb - (100.0 - relative_humidity) / 5.0
            sky_infrared = 5.67e-8 * (dry_bulb + 273.15) ** 4 * 0.72
            row = [
                str(year), str(current.month), str(current.day), str(hour), "0",
                "SYNTHETIC",
                f"{dry_bulb:.1f}", f"{dew_point:.1f}", f"{relative_humidity:.0f}",
                str(pressure), "0", "0", f"{sky_infrared:.0f}",
                f"{global_horizontal:.0f}", f"{direct_normal:.0f}", f"{diffuse:.0f}",
                "0", "0", "0", "0", "180", "2.0", "2", "2", "40.0", "77777",
                "9", "999999999", "10.0", "0.100", "0", "88", "0.180", "0.0", "1.0",
            ]
            lines.append(",".join(row))
    target.write_text("\n".join(lines) + "\n", encoding="latin-1")
    return target
